#!/usr/bin/env python3
"""Download chat prompts for on-policy self-distillation (build_data.py --prompts).

The NCM is trained to imitate the original model, so the best training data for chat is the original model's OWN
answers to chat prompts (generated by build_data.py on the GPU), not someone else's answers. This only fetches the
prompts:
  HuggingFaceTB/smol-smoltalk (test split, ~48 MB): the chat mix SmolLM2's small instruct models were tuned on
  tatsu-lab/alpaca (~24 MB): short instructions and factual questions
Writes OUT/prompts.jsonl and OUT/heldout_prompts.jsonl (the last --heldout rows of each source, never trained on),
one {"messages": [system?, user], "source": ...} per line.

  python -I fetch_prompts.py --out msdata/
"""
import argparse, json, os, random


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--heldout", type=int, default=200, help="held-out prompts per source")
    ap.add_argument("--max-chars", type=int, default=600, help="skip prompts longer than this (the prefix window is short)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    from huggingface_hub import hf_hub_download
    import pyarrow.parquet as pq
    cache = os.path.join(a.out, "_downloads")
    get = lambda repo, f: pq.read_table(hf_hub_download(repo, f, repo_type="dataset", local_dir=cache)).to_pylist()

    sources = {"smoltalk": [], "alpaca": []}
    for row in get("HuggingFaceTB/smol-smoltalk", "data/test-00000-of-00001.parquet"):
        msgs = row["messages"]
        k = next((i for i, m in enumerate(msgs) if m["role"] == "user"), None)
        if k is None:
            continue
        head = [m for m in msgs[:k] if m["role"] == "system"] + [msgs[k]]  # system prompt (if any) + first user turn
        if sum(len(m["content"]) for m in head) <= a.max_chars:
            sources["smoltalk"].append({"messages": head, "source": "smoltalk"})
    for row in get("tatsu-lab/alpaca", "data/train-00000-of-00001-a09b74b3ef9c3b56.parquet"):
        text = row["instruction"] + (("\n\n" + row["input"]) if row["input"] else "")
        if len(text) <= a.max_chars:
            sources["alpaca"].append({"messages": [{"role": "user", "content": text}], "source": "alpaca"})

    rng = random.Random(0)
    train, held = [], []
    for name, rows in sources.items():
        rng.shuffle(rows)
        held += rows[:a.heldout]
        train += rows[a.heldout:]
        print(f"{name}: {len(rows)} prompts ({a.heldout} held out)")
    rng.shuffle(train)
    for fn, rows in (("prompts.jsonl", train), ("heldout_prompts.jsonl", held)):
        with open(os.path.join(a.out, fn), "w") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"wrote {len(train)} training and {len(held)} held-out prompts to {a.out}")


if __name__ == "__main__":
    main()
